-- TV pairing. A TV browser starts a pairing (short code shown on screen + a secret it keeps),
-- a signed-in user claims the code for a room, and the TV's next poll with the secret receives
-- tokens for a fresh TV user that is a restricted member of that room. Only sha256(secret) is
-- stored. Rows are short-lived: deleted once tokens are delivered or after they expire.
CREATE TABLE IF NOT EXISTS tv_pairings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    secret_hash BYTEA NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Set together when a user claims the code.
    claimed_at TIMESTAMPTZ,
    room_id BIGINT REFERENCES rooms(id) ON DELETE CASCADE,
    tv_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    tv_device_id BIGINT,

    CONSTRAINT tv_pairings_code_unique UNIQUE (code),
    CONSTRAINT tv_pairings_secret_hash_unique UNIQUE (secret_hash)
);

CREATE INDEX IF NOT EXISTS idx_tv_pairings_expires_at ON tv_pairings(expires_at);

-- Paired TVs. Tokens issued to a TV are bound to its row and stop refreshing once revoked.
CREATE TABLE IF NOT EXISTS tv_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    paired_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,

    CONSTRAINT tv_devices_user_id_unique UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_tv_devices_room_id ON tv_devices(room_id);
